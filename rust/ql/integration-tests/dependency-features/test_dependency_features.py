import json
from textwrap import dedent

import commands
import pytest


@pytest.mark.parametrize(
    ("configurations", "reverse"),
    [
        pytest.param(
            configurations,
            reverse,
            marks=pytest.mark.ql_test(
                expected=f".{expected}{'.reversed' if reverse else ''}.expected"
            ),
            id=f"{name}{'-reversed' if reverse else ''}",
        )
        for name, expected, configurations in [
            ("more-features", "rich", [(["a", "b"], ["a"]), (["a"], ["a", "b"])]),
            ("equal-features", "tie", [(["a"], ["b"]), (["b"], ["a"])]),
        ]
        for reverse in [False, True]
    ],
)
def test_dependency_features(codeql, rust, cwd, configurations, reverse):
    """
    Two independent workspaces, `source/first` and `source/second`, share the
    local dependencies `alpha` and `beta`, but enable different Cargo features
    (their `Cargo.toml` are created in this test).

    Below is an overview of the files in the test setup.
    ```
    dependency-features/
    |-- dependencies/
    |   |-- alpha/
    |   |   |-- Cargo.toml
    |   |   `-- src/lib.rs       # feature-gated functions and invoke! macro
    |   `-- beta/
    |       |-- Cargo.toml
    |       `-- src/lib.rs       # feature-gated functions and invoke! macro
    |-- source/
    |   |-- first/
    |   |   |-- Cargo.toml       # generated by this test for each configuration
    |   |   `-- src/lib.rs       # calls alpha::invoke! and beta::invoke!
    |   `-- second/
    |       |-- Cargo.toml       # generated by this test for each configuration
    |       `-- src/lib.rs       # calls alpha::invoke! and beta::invoke!
    ```

    Each `src/lib.rs` file calls a macro from each dependency. The macros expand
    to different calls depending on the enabled features. The `functions.ql`
    query checks which calls and targets are extracted for the `src/lib.rs`
    files.
    """
    if reverse:
        configurations = configurations[::-1]
    for workspace, features in zip(["first", "second"], configurations):
        manifest = cwd / "source" / workspace / "Cargo.toml"
        manifest.write_text(
            dedent(f"""\
                [package]
                name = "{workspace}"
                version = "0.1.0"
                edition = "2024"

                [workspace]

                [dependencies]
                """)
            + "\n".join(
                f'{name} = {{ version = "=0.1.0", features = {json.dumps(enabled)} }}'
                for name, enabled in zip(["alpha", "beta"], features)
            )
            + "\n"
        )
        commands.run(f'cargo check --quiet --manifest-path "{manifest}"')
    codeql.database.create(source_root="source")
