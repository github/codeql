#!/bin/bash
# Generates type models for the unified analysis from `.swiftinterface` files.
#
# Usage:
#   scripts/generate-type-models.sh <interface-dir>
#   scripts/generate-type-models.sh --sdk <Module>...
#
# The first form uses all `.swiftinterface` files found in <interface-dir>. Each file should be
# named `<Module>.swiftinterface` or be placed in a `<Module>.swiftmodule` folder.
#
# The second form copies the interfaces of the given modules from the SDK reported by
# `xcrun --show-sdk-path` into a temporary folder (macOS only).
#
# Only types that are relevant to the existing source, sink, and summary models are exported.
# The output is written to ql/lib/ext/generated/swift-type-models.model.yml.
#
# The extractor pack must be built first, with scripts/create-extractor-pack.sh.
set -euo pipefail

cd "$(dirname "$0")/.."
UNIFIED_DIR="$(pwd)"
REPO_ROOT="$(cd .. && pwd)"

OUTPUT="$UNIFIED_DIR/ql/lib/ext/generated/swift-type-models.model.yml"
WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

if [[ "${1:-}" == "--sdk" ]]; then
  shift
  SDK="$(xcrun --show-sdk-path)"
  SRC_DIR="$WORK_DIR/src"
  mkdir -p "$SRC_DIR"
  for module in "$@"; do
    file="$(find -L "$SDK" -path "*/$module.swiftmodule/*" -name 'arm64e-apple-macos.swiftinterface' 2>/dev/null | head -n 1)"
    if [[ -z "$file" ]]; then
      file="$(find -L "$SDK" -path "*/$module.swiftmodule/*" -name 'arm64e-apple-ios-macabi.swiftinterface' 2>/dev/null | head -n 1)"
    fi
    if [[ -z "$file" ]]; then
      echo "Could not find interface for module $module" >&2
      exit 1
    fi
    cp "$file" "$SRC_DIR/$module.swiftinterface"
  done
elif [[ $# -eq 1 ]]; then
  SRC_DIR="$(cd "$1" && pwd)"
else
  sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//'
  exit 1
fi

codeql database create "$WORK_DIR/db" --overwrite --language=unified \
  --search-path "$UNIFIED_DIR/extractor-pack" --source-root "$SRC_DIR"

codeql query run --additional-packs="$REPO_ROOT" -d "$WORK_DIR/db" -o "$WORK_DIR/results.bqrs" \
  "$UNIFIED_DIR/ql/src/utils/modelgenerator/GenerateTypeModels.ql"

for result_set in typeModel summaryModel; do
  codeql bqrs decode --format=json --result-set="$result_set" "$WORK_DIR/results.bqrs" \
    > "$WORK_DIR/$result_set.json"
done

mkdir -p "$UNIFIED_DIR/ql/lib/ext/generated"
python3 - "$WORK_DIR" "$OUTPUT" <<'PYTHON'
import json, sys

work_dir, output = sys.argv[1:3]
lines = [
    "# Generated by unified/scripts/generate-type-models.sh. Do not edit by hand.",
    "extensions:",
]
for extensible in ["typeModel", "summaryModel"]:
    rows = json.load(open(f"{work_dir}/{extensible}.json")).get("tuples", [])
    rows = sorted(set(tuple(row) for row in rows))
    if not rows:
        continue
    lines += [
        "  - addsTo:",
        "      pack: codeql/unified-all",
        f"      extensible: {extensible}",
        "    data:",
    ]
    lines += ["      - " + json.dumps(list(row)) for row in rows]
open(output, "w").write("\n".join(lines) + "\n")
print(f"Wrote {output}")
PYTHON
