#!/usr/bin/env python3
"""Generate the sink vocabulary from the checked-in SwiftSyntax schema."""
import json
import pathlib
import re
import subprocess

root = pathlib.Path(__file__).resolve().parent.parent
schema = (root / "swift_node_types.yml").read_text().split("named:\n", 1)[1]
nodes = re.findall(r"^  (\w+):", schema, re.M)
fields = sorted(set(re.findall(r"^    (\w+)[?*]?:", schema, re.M)))
varying = set(nodes[nodes.index("_token") + 1:]) | {"stringSegment"}
nodes = nodes[:nodes.index("_token")]
keywords_file = root.parent / "swift-syntax-rs/swift/.build/checkouts/swift-syntax/Sources/SwiftSyntax/generated/Keyword.swift"
keywords = re.findall(r"^  case `?(\w+)`?\s*$", keywords_file.read_text(), re.M)
punctuation = {
    "Ampersand": "&", "Arrow": "->", "AtSign": "@", "Backslash": "\\", "Backtick": "`",
    "Colon": ":", "ColonColon": "::", "Comma": ",", "Ellipsis": "...", "Equal": "=",
    "ExclamationMark": "!", "InfixQuestionMark": "?", "LeftAngle": "<",
    "LeftBrace": "{", "LeftParen": "(", "LeftSquare": "[", "Period": ".",
    "Pound": "#", "RightAngle": ">", "RightBrace": "}", "RightParen": ")",
    "RightSquare": "]", "Semicolon": ";", "SingleQuote": "'",
    "StringQuote": '"', "MultilineStringQuote": '"""', "Wildcard": "_",
    "EndOfFile": "endOfFile",
    "RegexSlash": "/",
    "PoundIf": "#if", "PoundElseif": "#elseif", "PoundElse": "#else",
    "PoundEndif": "#endif", "PoundAvailable": "#available",
    "PoundUnavailable": "#unavailable",
    "PoundSourceLocationToken": "#sourceLocation",
}

def variant(name):
    return name[0].upper() + name[1:] if not name.startswith("_") else name[1:2].upper() + name[2:]

def keyword_variant(name):
    prefix = "Kw" + ("Upper" if name[0].isupper() else "")
    prefix += "Underscore" * (len(name) - len(name.lstrip("_")))
    return prefix + "".join(variant(part) for part in name.strip("_").split("_"))

entries = [(variant(n), n, False, True) for n in nodes]
entries += [(variant(n) + ("Token" if n == "stringSegment" else ""), n, True, True) for n in sorted(varying)]
entries += [(keyword_variant(n), n, True, False) for n in keywords]
entries += [(v, n, True, False) for v, n in punctuation.items()]
out = ["// Generated by scripts/generate-syntax-kinds.py; do not edit.",
       "#![allow(clippy::too_many_lines)]",
       "#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "#[repr(u16)]", "pub enum SyntaxKind {"]
out += [f"    {v}," for v, *_ in entries]
out += ["}", "impl SyntaxKind {", "    pub const ALL: &[Self] = &["]
out += [f"        Self::{v}," for v, *_ in entries]
out += ["    ];", "    pub const fn name(self) -> &'static str {", "        match self {"]
out += [f"            Self::{v} => {json.dumps(n)}," for v, n, *_ in entries]
out += ["        }", "    }", "    pub const fn is_token(self) -> bool {",
        f"        (self as u16) >= Self::{variant(sorted(varying)[0])} as u16", "    }"]
out += ["    pub const fn is_named(self) -> bool {",
        f"        (self as u16) < Self::{keyword_variant(keywords[0])} as u16", "    }"]
out += ["    pub(crate) fn keyword(text: &str) -> Option<Self> {", "        Some(match text {"]
out += [f'            "{n}" => Self::{keyword_variant(n)},' for n in keywords]
out += ["            _ => return None,", "        })", "    }", "}"]
out += ["#[derive(Clone, Copy, Debug, PartialEq, Eq)]", "#[repr(u16)]", "pub enum FieldKind {"]
out += [f"    {variant(n)}," for n in fields]
out += ["}", "impl FieldKind {", "    pub const ALL: &[Self] = &["]
out += [f"        Self::{variant(n)}," for n in fields]
out += ["    ];", "    pub const fn name(self) -> &'static str {", "        match self {"]
out += [f'            Self::{variant(n)} => "{n}",' for n in fields]
out += ["        }", "    }", "}"]
(root / "src/kinds.rs").write_text("\n".join(out) + "\n")
subprocess.run(["rustfmt", "--edition", "2024", str(root / "src/kinds.rs")], check=True)
